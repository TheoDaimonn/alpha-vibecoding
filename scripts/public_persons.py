def relabel_stems() -> dict[str, str]:
    stems = {}
    for _, last, _, _ in PUBLIC_PERSONS:
        for part in last.split("-"):
            if part in NON_DECLINABLE or part in RELABEL_EXCLUDED or len(part) < 5:
                continue
            low = part.lower()
            if low.endswith(("ский", "цкий", "ской")):
                stem = low[:-2]
            elif low.endswith("ая"):
                stem = low[:-2]
            elif low.endswith(("ой", "ый", "ий")):
                stem = low[:-2]
            elif low.endswith(("ов", "ев", "ёв", "ин", "ын")):
                stem = low
            elif low.endswith("ь"):
                stem = low[:-1]
            elif low.endswith("а"):
                stem = low[:-1]
            else:
                stem = low
            if len(stem) >= 5:
                stems[stem] = part
    return stems
